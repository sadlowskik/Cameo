#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const manifest = JSON.parse(readFileSync(resolve(root, "release-manifest.json"), "utf8"));

function fail(message) {
  console.error(`Release manifest check failed: ${message}`);
  process.exit(1);
}

function cargoVersion(path, section) {
  const source = readFileSync(resolve(root, path), "utf8");
  const body = source.match(new RegExp(`\\[${section.replace(".", "\\.")}\\]([\\s\\S]*?)(?:\\n\\[|$)`))?.[1];
  return body?.match(/^version\s*=\s*"([^"]+)"/m)?.[1];
}

function packageVersion(path) {
  return JSON.parse(readFileSync(resolve(root, path), "utf8")).version;
}

function expect(label, actual, expected) {
  if (actual !== expected) fail(`${label} is ${actual ?? "missing"}; expected ${expected}`);
}

expect("Cameo tag", manifest.cameo.tag, `v${manifest.cameo.version}`);
expect("Cameo Cargo version", cargoVersion("Cargo.toml", "workspace.package"), manifest.cameo.version);
expect("Knossos tag", manifest.knossos.tag, `v${manifest.knossos.version}`);
expect("Knossos Cargo version", cargoVersion("daedalus/knossos-rs/Cargo.toml", "package"), manifest.knossos.version);
expect("Field package version", packageVersion("daedalus/field/package.json"), manifest.field.version);
expect("Field server version", packageVersion("daedalus/field/server/package.json"), manifest.field.version);
expect("Field web version", packageVersion("daedalus/field/web/package.json"), manifest.field.version);
expect("Knossos VS Code version", packageVersion("daedalus/knossos-rs/editor/vscode/package.json"), manifest.knossos.version);

const fieldLock = JSON.parse(readFileSync(resolve(root, "daedalus/field/package-lock.json"), "utf8"));
for (const key of ["", "server", "web"]) {
  expect(`Field lock package ${key || "root"}`, fieldLock.packages[key]?.version, manifest.field.version);
}

expect("Cameo release status", manifest.cameo.release_status, "unpublished");
expect("Cameo ISO status", manifest.cameo.iso.status, "ci-candidate");
expect("Cameo candidate validation", manifest.cameo.iso.candidate.validation, "passed");
expect("Cameo candidate hardware status", manifest.cameo.iso.candidate.hardware_status, "unverified");
expect("Knossos release status", manifest.knossos.release_status, "unpublished");
expect("Knossos Windows artifact status", manifest.knossos.artifacts.windows_x86_64.status, "rebuild-required");
expect("Knossos Linux artifact status", manifest.knossos.artifacts.linux_x86_64.status, "rebuild-required");

const releaseIndex = manifest.cameo.release_index;
const knossosVersion = manifest.knossos.version;
const candidate = manifest.cameo.iso.candidate;
const full = candidate.artifacts.full;
const lite = candidate.artifacts.lite;

function gib(bytes) {
  return `${(bytes / (1024 ** 3)).toFixed(2)} GiB`;
}

function displayDate(iso) {
  const value = new Date(iso);
  if (Number.isNaN(value.valueOf())) fail(`invalid release date: ${iso}`);
  return new Intl.DateTimeFormat("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    timeZone: "UTC",
  }).format(value);
}

for (const [edition, artifact] of Object.entries(candidate.artifacts)) {
  if (!Number.isSafeInteger(artifact.artifact_id) || artifact.artifact_id <= 0) {
    fail(`${edition} artifact id is invalid`);
  }
  if (!Number.isSafeInteger(artifact.size_bytes) || artifact.size_bytes <= 0) {
    fail(`${edition} artifact size is invalid`);
  }
  const url = new URL(artifact.download_url);
  if (url.protocol !== "https:" || url.hostname !== "github.com") {
    fail(`${edition} artifact URL must be an HTTPS github.com URL`);
  }
}

const rendered = `<!-- RELEASES:START — generated by scripts/render-releases.mjs -->
    <article class="install">
      <h3>1 · Download the image</h3>
      <p><span class="build-state"><i aria-hidden="true"></i>Candidate build passed</span> Both Cameo images built successfully on ${displayDate(candidate.built_at)} from commit <code>${candidate.commit}</code>. The workflow passed image checks, required-file checks, and a QEMU userspace boot. This is a CI candidate, not yet a tagged release or AMD hardware qualification.</p>
      <div class="eds">
        <div class="ed rec">
          <div class="ed-h"><span class="ed-name">Universal</span><span class="tag-rec">${gib(full.size_bytes)} · Vulkan + ROCm</span></div>
          <p>Primary appliance candidate. Vulkan is the broad compatibility path; ROCm is included for supported AMD hardware.</p>
          <div class="ed-picks"><span><b>CI:</b> passed · run #${candidate.run_number}</span><span><b>Available through:</b> ${displayDate(full.expires_at)}</span></div>
          <a class="btn-primary" href="${full.download_url}" rel="noopener">
            <svg class="ico" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4"/><polyline points="7 10 12 15 17 10"/><line x1="12" x2="12" y1="15" y2="3"/></svg>
            Download Universal candidate
          </a>
          <p>GitHub sign-in may be required. The artifact includes its SHA-256 checksum.</p>
        </div>
        <div class="ed">
          <div class="ed-h"><span class="ed-name">Lite</span><span class="tag-s">${gib(lite.size_bytes)} · Vulkan only</span></div>
          <p>Smaller candidate for known Vulkan-only and lower-end AMD systems. It carries the same Cameo and Knossos runtime.</p>
          <div class="ed-picks"><span><b>CI:</b> passed · run #${candidate.run_number}</span><span><b>Available through:</b> ${displayDate(lite.expires_at)}</span></div>
          <a class="btn" href="${lite.download_url}" rel="noopener">Download Lite candidate</a>
          <p>GitHub sign-in may be required. The artifact includes its SHA-256 checksum.</p>
        </div>
      </div>
      <div class="release-links"><a href="${candidate.run_url}" rel="noopener">Inspect workflow evidence</a><a href="${releaseIndex}" rel="noopener">Public releases</a></div>
    </article>

    <details class="devbox">
      <summary>Knossos standalone (Windows + Linux)</summary>
      <article class="install">
      <h3>Standalone harness</h3>
      <p>Next beta: <code style="font-family:var(--mono);font-size:.9em;color:var(--amber)">v${knossosVersion}</code>. Needs a model — Ollama, Anthropic, Gemini, Groq, or a running Cameo box. Matching standalone artifacts are being rebuilt; no mislabeled binary is offered here. A Windows paired-control reward-eval ran on 2026-09-08 against <code style="font-family:var(--mono);font-size:.9em;color:var(--amber)">gemini-3.6-flash</code>; both arms stopped on token-budget and tool-calling failures before 8/8, so that run is retained evidence, not a capability score.</p>
      <div class="eds">
        <div class="ed rec">
          <div class="ed-h"><span class="ed-name">Windows</span><span class="tag-rec">x86_64 · beta</span></div>
          <p>Knossos ${knossosVersion} CLI plus constitution and license. Build pending. Source-tree tests passed; the live 8-case matrix did not complete.</p>
          <a class="btn-primary" href="${manifest.knossos.release_url}" rel="noopener">View Knossos releases</a>
          <p>A download appears only after its version and checksum pass the release gate.</p>
        </div>
        <div class="ed">
          <div class="ed-h"><span class="ed-name">Linux</span><span class="tag-s">x86_64 · beta</span></div>
          <p>Linux x86_64 build pending. macOS is not yet published.</p>
          <a class="btn" href="${manifest.knossos.release_url}" rel="noopener">View Knossos releases</a>
        </div>
      </div>
      </article>
    </details>
<!-- RELEASES:END -->`;

const sitePath = resolve(root, "site/index.html");
const site = readFileSync(sitePath, "utf8");
const pattern = /<!-- RELEASES:START[^]*?<!-- RELEASES:END -->/;
if (!pattern.test(site)) fail("site/index.html is missing RELEASES markers");
const updated = site.replace(pattern, rendered);

if (check) {
  if (updated !== site) fail("site/index.html is stale; run node scripts/render-releases.mjs");
  console.log("Release manifest and site downloads are current.");
} else {
  writeFileSync(sitePath, updated, "utf8");
  console.log("Rendered release metadata into site/index.html.");
}
